    fn default_init_val(iec_type: &str, init_st: Option<&str>) -> String {
        if let Some(init) = init_st {
            let trimmed = init.trim();
            if trimmed.eq_ignore_ascii_case("TRUE") {
                return "true".to_string();
            } else if trimmed.eq_ignore_ascii_case("FALSE") {
                return "false".to_string();
            } else {
                return trimmed.to_string();
            }
        }
        match iec_type.to_ascii_uppercase().as_str() {
            "BOOL" => "false".to_string(),
            "BYTE" | "WORD" | "DWORD" | "LWORD" | "SINT" | "INT" | "DINT" | "LINT" | "USINT"
            | "UINT" | "UDINT" | "ULINT" | "TIME" => "0".to_string(),
            "REAL" | "LREAL" => "0.0".to_string(),
            _ => String::new(),
        }
    }

    fn parse_time_interval_ns(val: &str) -> i64 {
        let upper = val.to_ascii_uppercase();
        let digits: String = upper.chars().filter(|c| c.is_ascii_digit()).collect();
        let num: i64 = digits.parse().unwrap_or(10);
        if upper.contains("MS") {
            num * 1_000_000
        } else if upper.contains('S') {
            num * 1_000_000_000
        } else if upper.contains('M') {
            num * 60_000_000_000
        } else {
            num * 1_000_000
        }
    }

    fn transpile_body_lines(body_lines: &[&str]) -> String {
        let mut cpp_lines = Vec::new();
        let mut in_case = false;
        let mut first_case_arm = true;

        for line_raw in body_lines {
            let mut line = line_raw.trim().to_string();
            while let Some(start) = line.find("(*") {
                if let Some(end) = line[start..].find("*)") {
                    line = format!("{}{}", &line[..start], &line[start + end + 2..])
                        .trim()
                        .to_string();
                } else {
                    break;
                }
            }
            if line.is_empty() {
                continue;
            }

            let upper = line.to_ascii_uppercase();

            if upper.starts_with("CASE ") && upper.contains(" OF") {
                if let Some(of_idx) = upper.find(" OF") {
                    let expr = line[5..of_idx].trim();
                    cpp_lines.push(format!("switch ({}) {{", expr));
                    in_case = true;
                    first_case_arm = true;
                    continue;
                }
            }

            if upper.starts_with("END_CASE") {
                if in_case {
                    cpp_lines.push("break;\n    }".to_string());
                    in_case = false;
                }
                continue;
            }

            if in_case && line.contains(':') {
                let prefix = line[..line.find(':').unwrap()].trim();
                if prefix.chars().all(|c| c.is_ascii_digit()) {
                    if !first_case_arm {
                        cpp_lines.push("break;".to_string());
                    }
                    first_case_arm = false;
                    cpp_lines.push(format!("case {}:", prefix));
                    continue;
                }
            }

            if upper.starts_with("ELSE") {
                if in_case {
                    if !first_case_arm {
                        cpp_lines.push("break;".to_string());
                    }
                    cpp_lines.push("default:".to_string());
                    continue;
                } else {
                    cpp_lines.push("} else {".to_string());
                    continue;
                }
            }

            if upper.starts_with("IF ") && upper.contains(" THEN") {
                if let Some(then_idx) = upper.find(" THEN") {
                    let cond = line[3..then_idx].trim();
                    let cond_cpp = Self::replace_logical_operators(cond);
                    cpp_lines.push(format!("if ({}) {{", cond_cpp));
                    continue;
                }
            }

            if upper.starts_with("ELSIF ") && upper.contains(" THEN") {
                if let Some(then_idx) = upper.find(" THEN") {
                    let cond = line[6..then_idx].trim();
                    let cond_cpp = Self::replace_logical_operators(cond);
                    cpp_lines.push(format!("}} else if ({}) {{", cond_cpp));
                    continue;
                }
            }

            if upper.starts_with("END_IF") {
                cpp_lines.push("}".to_string());
                continue;
            }

            if line.contains('(') && line.ends_with(");") && line.contains(":=") {
                let open = line.find('(').unwrap();
                let close = line.rfind(')').unwrap();
                let fb_inst = line[..open].trim();
                let args_str = &line[open + 1..close];
                for p in args_str.split(',') {
                    if let Some(eq) = p.find(":=") {
                        let param = p[..eq].trim();
                        let val = p[eq + 2..].trim();
                        let val_cpp = Self::replace_literals(val);
                        cpp_lines.push(format!("{}.{} = {};", fb_inst, param, val_cpp));
                    }
                }
                cpp_lines.push(format!("{}();", fb_inst));
                continue;
            }

            if line.contains(":=") {
                let stmt = line.trim_end_matches(';').trim();
                if let Some(eq) = stmt.find(":=") {
                    let target = stmt[..eq].trim();
                    let expr = stmt[eq + 2..].trim();
                    let expr_lit = Self::replace_literals(expr);
                    let expr_cpp = Self::replace_logical_operators(&expr_lit);
                    cpp_lines.push(format!("{} = {};", target, expr_cpp));
                    continue;
                }
            }

            cpp_lines.push(line);
        }

        cpp_lines.join("\n    ")
    }

    fn replace_literals(val: &str) -> String {
        let upper = val.to_ascii_uppercase();
        if upper.starts_with("T#") {
            let digits: String = upper.chars().filter(|c| c.is_ascii_digit()).collect();
            let num: i64 = digits.parse().unwrap_or(0);
            let mult = if upper.contains("MS") {
                1_000_000
            } else if upper.contains('S') {
                1_000_000_000
            } else if upper.contains('M') {
                60_000_000_000
            } else {
                1_000_000
            };
            return format!("{}LL", num * mult);
        }
        let words: Vec<&str> = val.split_whitespace().collect();
        let mut out = Vec::new();
        for w in words {
            if w.eq_ignore_ascii_case("TRUE") {
                out.push("true");
            } else if w.eq_ignore_ascii_case("FALSE") {
                out.push("false");
            } else {
                out.push(w);
            }
        }
        out.join(" ")
    }

    fn replace_logical_operators(expr: &str) -> String {
        let mut result = String::new();
        let mut chars = expr.chars().peekable();

        while let Some(c) = chars.next() {
            if c.is_ascii_alphabetic() || c == '_' {
                let mut word = String::new();
                word.push(c);
                while let Some(&nc) = chars.peek() {
                    if nc.is_ascii_alphanumeric() || nc == '_' || nc == '.' {
                        word.push(chars.next().unwrap());
                    } else {
                        break;
                    }
                }
                let upper = word.to_ascii_uppercase();
                match upper.as_str() {
                    "NOT" => result.push('!'),
                    "AND" => result.push_str("&&"),
                    "OR" => result.push_str("||"),
                    "TRUE" => result.push_str("true"),
                    "FALSE" => result.push_str("false"),
                    _ => result.push_str(&word),
                }
            } else if c == '=' {
                // If previous char wasn't <, >, !, and next char isn't =, replace with ==
                if !result.ends_with('<') && !result.ends_with('>') && !result.ends_with('!') {
                    if chars.peek() == Some(&'=') {
                        result.push('=');
                    } else {
                        result.push_str("==");
                    }
                } else {
                    result.push('=');
                }
            } else {
                result.push(c);
            }
        }
        result
    }

