//! In-controller Structured Text (ST) compilation pipeline and C++ artifact builder.

use crate::error::StrucppError;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use tracing::{debug, info};

pub const DEFAULT_STRUCPP_CLI: &str = "/home/adrian/Projects/openplc-editor/node_modules/strucpp/dist/node/cli.js";
pub const DEFAULT_STRUCPP_INCLUDE: &str = "/home/adrian/Projects/openplc-editor/node_modules/strucpp/src/runtime/include";
pub const DEFAULT_CXX_COMPILER: &str = "/usr/bin/g++";

/// Configuration parameters for the STruC++ compiler pipeline.
#[derive(Debug, Clone)]
pub struct CompilerConfig {
    pub strucpp_cli: PathBuf,
    pub strucpp_include: PathBuf,
    pub cxx_compiler: PathBuf,
    pub output_dir: PathBuf,
    pub enable_debug: bool,
    pub opt_level: String,
}

impl Default for CompilerConfig {
    fn default() -> Self {
        Self {
            strucpp_cli: PathBuf::from(DEFAULT_STRUCPP_CLI),
            strucpp_include: PathBuf::from(DEFAULT_STRUCPP_INCLUDE),
            cxx_compiler: PathBuf::from(DEFAULT_CXX_COMPILER),
            output_dir: std::env::temp_dir().join("mythos_strucpp_builds"),
            enable_debug: true,
            opt_level: "-O3".to_string(),
        }
    }
}

/// Output artifacts generated by compilation.
#[derive(Debug, Clone)]
pub struct CompilationArtifacts {
    pub source_hash: String,
    pub cpp_source: PathBuf,
    pub cpp_header: PathBuf,
    pub glue_source: PathBuf,
    pub shared_library: PathBuf,
}

/// Structured Text Compiler managing code-generation and shared object compilation.
pub struct StrucppCompiler {
    config: CompilerConfig,
}

impl StrucppCompiler {
    pub fn new(config: CompilerConfig) -> Self {
        if !config.output_dir.exists() {
            let _ = fs::create_dir_all(&config.output_dir);
        }
        Self { config }
    }

    /// Calculate SHA-256 hash of Structured Text source to enable zero-recompilation caching.
    pub fn compute_hash(source_st: &str) -> String {
        use std::collections::hash_map::DefaultHasher;
        use std::hash::{Hash, Hasher};
        // Use crc32 or sha256 formatted hex
        let mut hasher = crc32fast::Hasher::new();
        hasher.update(source_st.as_bytes());
        let crc = hasher.finalize();

        // Also hash with std hasher to avoid collision
        let mut s_hasher = DefaultHasher::new();
        source_st.hash(&mut s_hasher);
        let s_hash = s_hasher.finish();

        format!("{:08x}{:016x}", crc, s_hash)
    }

    /// Compile IEC 61131-3 Structured Text source into a native C++17 shared library (`.so`).
    pub fn compile_source(&self, source_st: &str) -> Result<CompilationArtifacts, StrucppError> {
        let hash = Self::compute_hash(source_st);
        let build_dir = self.config.output_dir.join(format!("build_{}", hash));
        fs::create_dir_all(&build_dir)?;

        let so_path = build_dir.join("logic.so");
        let cpp_path = build_dir.join("generated.cpp");
        let hpp_path = build_dir.join("generated.hpp");
        let glue_path = build_dir.join("glue.cpp");

        // If library already exists, return cached artifact
        if so_path.exists() {
            info!("Returning cached logic artifact for hash {}", hash);
            return Ok(CompilationArtifacts {
                source_hash: hash,
                cpp_source: cpp_path,
                cpp_header: hpp_path,
                glue_source: glue_path,
                shared_library: so_path,
            });
        }

        // 1. Write ST source to disk
        let st_file = build_dir.join("program.st");
        fs::write(&st_file, source_st)?;

        // 2. Invoke STruC++ node CLI
        debug!("Running STruC++ CLI on {}", st_file.display());
        let mut cmd = Command::new("node");
        cmd.arg(&self.config.strucpp_cli)
            .arg(&st_file)
            .arg("-o")
            .arg(&cpp_path);

        if self.config.enable_debug {
            cmd.arg("--debug");
        }

        let output = cmd.output().map_err(|e| StrucppError::CompilationFailed {
            reason: format!("Failed to spawn STruC++ node CLI: {}", e),
        })?;

        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            let stdout = String::from_utf8_lossy(&output.stdout);
            return Err(StrucppError::CompilationFailed {
                reason: format!("STruC++ transpiler failed: {}\n{}", stderr, stdout),
            });
        }

        // 3. Generate Glue C++ code referencing the generated header
        let glue_code = self.generate_glue_cpp(&hpp_path);
        fs::write(&glue_path, glue_code)?;

        // 4. Compile to shared library using g++ / clang++
        debug!("Compiling C++ shared library with {}", self.config.cxx_compiler.display());
        let mut cxx_cmd = Command::new(&self.config.cxx_compiler);
        cxx_cmd
            .arg("-std=c++17")
            .arg(&self.config.opt_level)
            .arg("-fPIC")
            .arg("-shared")
            .arg(format!("-I{}", self.config.strucpp_include.display()))
            .arg(format!("-I{}", build_dir.display()))
            .arg(&cpp_path)
            .arg(&glue_path)
            .arg("-o")
            .arg(&so_path)
            .arg("-lpthread");

        let cxx_output = cxx_cmd.output().map_err(|e| StrucppError::CppCompilationFailed {
            reason: format!("Failed to invoke C++ compiler: {}", e),
        })?;

        if !cxx_output.status.success() {
            let stderr = String::from_utf8_lossy(&cxx_output.stderr);
            let stdout = String::from_utf8_lossy(&cxx_output.stdout);
            return Err(StrucppError::CppCompilationFailed {
                reason: format!("g++ compilation failed: {}\n{}", stderr, stdout),
            });
        }

        info!("Successfully compiled logic binary to {}", so_path.display());
        Ok(CompilationArtifacts {
            source_hash: hash,
            cpp_source: cpp_path,
            cpp_header: hpp_path,
            glue_source: glue_path,
            shared_library: so_path,
        })
    }

    /// Generate glue C++ bridge file
    fn generate_glue_cpp(&self, hpp_path: &Path) -> String {
        let hpp_abs = hpp_path.canonicalize().unwrap_or_else(|_| hpp_path.to_path_buf());
        let hpp_str = hpp_abs.display().to_string();
        let inc_dir = self.config.strucpp_include.display().to_string();

        // Dynamically discover the configuration class name from the generated header
        let hpp_content = fs::read_to_string(hpp_path).unwrap_or_default();
        let mut config_class = "Configuration_CONFIG0".to_string();
        for line in hpp_content.lines() {
            if line.contains(": public ConfigurationInstance") {
                if let Some(pos) = line.find("class ") {
                    let after = &line[pos + 6..];
                    if let Some(end) = after.find(':') {
                        config_class = after[..end].trim().to_string();
                        break;
                    }
                }
            }
        }

        format!(
            r#"#include <cstdint>
#include <cstddef>
#include <pthread.h>
#include "{inc_dir}/debug_table.hpp"

namespace strucpp {{
namespace debug {{
    const uint8_t debug_array_count = 0;
    const uint16_t debug_array_counts[1] = {{ 0 }};
    const Entry* const debug_arrays[1] = {{ nullptr }};
    const RetainVar retain_vars[1] = {{ {{ 0, 0 }} }};
    const uint16_t retain_var_count = 0;
    const uint32_t retain_layout_hash = 0;
}}
}}

#define STRUCPP_V4_DEBUG_EXPORTS_DEFINE
#include "{inc_dir}/debug_dispatch.hpp"
#include "{hpp_str}"

namespace strucpp {{
    pthread_mutex_t* g_image_tables_mutex_ptr = nullptr;
    pthread_mutex_t* g_global_vars_mutex_ptr  = nullptr;
}}

static strucpp::{config_class} g_config;

extern "C" strucpp::ConfigurationInstance* strucpp_get_config(void) {{
    return &g_config;
}}

extern "C" void strucpp_set_locks(pthread_mutex_t* image_tables_mutex,
                                  pthread_mutex_t* global_vars_mutex) {{
    strucpp::g_image_tables_mutex_ptr = image_tables_mutex;
    strucpp::g_global_vars_mutex_ptr  = global_vars_mutex;
}}

extern "C" strucpp::LocatedVar* strucpp_get_located_vars(uint32_t* count) {{
    if (count) {{
        *count = strucpp::locatedVarsCount;
    }}
    return strucpp::locatedVars;
}}

extern "C" uint32_t strucpp_get_located_vars_count(void) {{
    return strucpp::locatedVarsCount;
}}

extern "C" void strucpp_step_cycle(void) {{
    size_t r_cnt = g_config.get_resource_count();
    strucpp::ResourceInstance* resources = g_config.get_resources();
    for (size_t r = 0; r < r_cnt; ++r) {{
        for (size_t t = 0; t < resources[r].task_count; ++t) {{
            strucpp::TaskInstance& task = resources[r].tasks[t];
            for (size_t p = 0; p < task.program_count; ++p) {{
                task.programs[p]->sync_in();
                task.programs[p]->run();
                task.programs[p]->sync_out();
            }}
        }}
    }}
}}
"#
        )
    }
}
